#!/usr/bin/env node
'use strict';

/**
 * `npm run setup` — interactive first-run wizard for Mail Workflow.
 *
 * Goal: a newcomer runs one command and ends up with a valid `.env`, without
 * having read any documentation first.
 *
 * Design notes:
 *  - Node built-ins only (it must run before `npm install` if needed).
 *  - The generated `.env` is rendered FROM `.env.example`, so its comments,
 *    section headers and variable order survive.
 *  - Nothing is written until the very last step, and the write is atomic
 *    (temp file + rename), so Ctrl+C can never leave a half-written `.env`.
 *  - Secret values are never echoed back or printed in summaries.
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const readline = require('node:readline/promises');

const {
  ENV_PATH,
  ENV_BACKUP_PATH,
  ENV_EXAMPLE_PATH,
  PROJECT_ROOT,
  MIN_NODE_MAJOR,
  DEFAULT_PORT,
  MANAGED_KEYS,
  color,
  ignoreEpipe,
  nodeMajor,
  isNodeSupported,
  readEnvFile,
  isBlank,
  renderEnvFromTemplate,
  localUris,
} = require('./lib/env');

/** Exit code used when the user aborts with Ctrl+C (128 + SIGINT). */
const EXIT_CANCELLED = 130;

/** Fallback template, used only if `.env.example` is missing or unreadable. */
const FALLBACK_TEMPLATE = [
  '# Mail Workflow — environment',
  '# Generated by `npm run setup`. NEVER commit this file.',
  '',
  'SESSION_SECRET=',
  'APP_ORIGIN=',
  'REDIS_URL=',
  'PORT=3000',
  '# NODE_ENV=production',
  '',
  '# --- Gmail OAuth (Google Cloud Console) ---',
  'GMAIL_CLIENT_ID=',
  'GMAIL_CLIENT_SECRET=',
  'GMAIL_REDIRECT_URI=',
  '',
  '# --- Outlook OAuth (Azure AD) ---',
  'OUTLOOK_CLIENT_ID=',
  'OUTLOOK_CLIENT_SECRET=',
  'OUTLOOK_TENANT_ID=common',
  'OUTLOOK_REDIRECT_URI=',
  '',
  '# --- AI proxy (/api/ai/*) ---',
  'ALLOW_LOCAL_AI=',
  'OLLAMA_API_KEY=',
  '',
].join('\n');

// --- Small output helpers ----------------------------------------------------

ignoreEpipe();

const say = (line = '') => process.stdout.write(`${line}\n`);
const rule = () => say(color.dim('-'.repeat(72)));

/**
 * Print a numbered section title.
 * @param {number} step
 * @param {string} title
 */
function section(step, title) {
  say();
  say(color.bold(`[${step}] ${title}`));
  rule();
}

// --- Prompt helpers ----------------------------------------------------------

/**
 * Ask a free-text question.
 * @param {readline.Interface} rl
 * @param {string} question
 * @param {{defaultValue?: string, required?: boolean, validate?: (v: string) => string|null}} [opts]
 * @returns {Promise<string>}
 */
async function ask(rl, question, opts = {}) {
  const { defaultValue = '', required = false, validate } = opts;
  for (;;) {
    const suffix = defaultValue ? ` ${color.dim(`[${defaultValue}]`)}` : '';
    // Values are trimmed: pasted credentials very often carry trailing spaces
    // or a stray newline, which is a real and confusing failure mode.
    const answer = (await rl.question(`${question}${suffix} > `)).trim();
    const value = answer === '' ? defaultValue : answer;
    if (required && value === '') {
      say(color.red('    This value is required.'));
      continue;
    }
    if (validate) {
      const problem = validate(value);
      if (problem) {
        say(color.red(`    ${problem}`));
        continue;
      }
    }
    return value;
  }
}

/**
 * Ask a yes/no question.
 * @param {readline.Interface} rl
 * @param {string} question
 * @param {boolean} [defaultYes]
 * @returns {Promise<boolean>}
 */
async function askYesNo(rl, question, defaultYes = false) {
  const hint = defaultYes ? 'Y/n' : 'y/N';
  for (;;) {
    const answer = (await rl.question(`${question} ${color.dim(`(${hint})`)} > `))
      .trim()
      .toLowerCase();
    if (answer === '') return defaultYes;
    if (['y', 'yes'].includes(answer)) return true;
    if (['n', 'no'].includes(answer)) return false;
    say(color.red('    Please answer "y" or "n".'));
  }
}

/**
 * Ask the user to pick one entry from a numbered list.
 * @param {readline.Interface} rl
 * @param {string} question
 * @param {string[]} options
 * @param {number} [defaultIndex] Zero-based.
 * @returns {Promise<number>} Zero-based index of the chosen option.
 */
async function askChoice(rl, question, options, defaultIndex = 0) {
  say(question);
  options.forEach((label, index) => say(`    ${index + 1}) ${label}`));
  for (;;) {
    const answer = (await rl.question(`  Choice ${color.dim(`[${defaultIndex + 1}]`)} > `)).trim();
    if (answer === '') return defaultIndex;
    const picked = Number.parseInt(answer, 10);
    if (Number.isInteger(picked) && picked >= 1 && picked <= options.length) {
      return picked - 1;
    }
    say(color.red(`    Enter a number between 1 and ${options.length}.`));
  }
}

// --- Validators --------------------------------------------------------------

/**
 * Validate a TCP port entered by the user.
 * @param {string} value
 * @returns {string|null} An error message, or null when valid.
 */
function validatePort(value) {
  const port = Number.parseInt(value, 10);
  if (!Number.isInteger(port) || String(port) !== value.trim()) {
    return 'Enter a number, e.g. 3000.';
  }
  if (port < 1 || port > 65535) return 'A port must be between 1 and 65535.';
  if (port < 1024) {
    return 'Ports below 1024 need administrator privileges. Pick 3000 or higher.';
  }
  return null;
}

/**
 * Validate a redis:// URL entered by the user.
 * @param {string} value
 * @returns {string|null}
 */
function validateRedisUrl(value) {
  try {
    const url = new URL(value);
    if (!['redis:', 'rediss:'].includes(url.protocol)) {
      return 'The URL must start with redis:// or rediss://';
    }
    if (!url.hostname) return 'The URL has no host.';
    return null;
  } catch {
    return 'Not a valid URL. Example: redis://localhost:6379';
  }
}

